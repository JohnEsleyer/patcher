package main

import (
	"fmt"
	"html"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	pathAttrRegex     = regexp.MustCompile(`(?i)\bpath\s*=\s*["'\x{201c}]([^"'\x{201d}]+)["'\x{201d}]`)
	tagStartRegex     = regexp.MustCompile("(?i)\x3c" + "(fi" + "le|rep" + "lace|del" + "ete)\\b")
	searchRegex       = regexp.MustCompile("(?s)\x3c" + "sea" + "rch\\s*>(.*?)\x3c/" + "sea" + "rch\\s*>")
	withRegex         = regexp.MustCompile("(?s)\x3c" + "wi" + "th\\s*>(.*?)\x3c/" + "wi" + "th\\s*>")
	topLevelDirective = regexp.MustCompile("(?m)^\x3c" + "(fi" + "le|rep" + "lace|del" + "ete)\\b[^>]*\\bpath\\s*=")
)

func cleanContent(s string) string {
	s = strings.ReplaceAll(s, "\u201c", "\"")
	s = strings.ReplaceAll(s, "\u201d", "\"")
	s = strings.ReplaceAll(s, "\u2018", "'")
	s = strings.ReplaceAll(s, "\u2019", "'")
	if strings.Contains(s, "&"+"lt;") || strings.Contains(s, "&"+"gt;") {
		s = html.UnescapeString(s)
	}
	return s
}

// trimTagNewlines strips a single leading newline after opening tag and trailing newline before closing tag
func trimTagNewlines(s string) string {
	if strings.HasPrefix(s, "\r\n") {
		s = s[2:]
	} else if strings.HasPrefix(s, "\n") {
		s = s[1:]
	}

	if strings.HasSuffix(s, "\r\n") {
		s = s[:len(s)-2]
	} else if strings.HasSuffix(s, "\n") {
		s = s[:len(s)-1]
	}
	return s
}

// stripCodeFences removes accidental markdown code block wrappers generated by LLMs
func stripCodeFences(s string) string {
	trimmed := strings.TrimSpace(s)
	if !strings.HasPrefix(trimmed, "```") {
		return s
	}
	lines := strings.Split(s, "\n")
	startIdx := -1
	endIdx := -1

	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])
		if line != "" {
			if strings.HasPrefix(line, "```") {
				startIdx = i
			}
			break
		}
	}
	for i := len(lines) - 1; i >= 0; i-- {
		line := strings.TrimSpace(lines[i])
		if line != "" {
			if strings.HasPrefix(line, "```") {
				endIdx = i
			}
			break
		}
	}

	if startIdx != -1 && endIdx != -1 && startIdx < endIdx {
		return strings.Join(lines[startIdx+1:endIdx], "\n")
	}
	return s
}

func lineAtOffset(s string, offset int) int {
	if offset > len(s) {
		offset = len(s)
	}
	return strings.Count(s[:offset], "\n") + 1
}

func parsePatch(content string) ([]Action, []string) {
	var actions []Action
	var errs []string

	pos := 0
	for {
		loc := tagStartRegex.FindStringIndex(content[pos:])
		if loc == nil {
			break
		}

		startIdx := pos + loc[0]
		lineNo := lineAtOffset(content, startIdx)

		// Determine which tag opened
		openTagEnd := strings.Index(content[startIdx:], ">")
		if openTagEnd == -1 {
			errs = append(errs, fmt.Sprintf("Line %d: Malformed unclosed tag header", lineNo))
			break
		}
		openTagEnd += startIdx + 1
		header := content[startIdx:openTagEnd]

		// Ignore self-closing tags used in conversational examples
		trimmedHeader := strings.TrimSpace(header)
		isSelfClosing := strings.HasSuffix(trimmedHeader, "/>")

		pathMatch := pathAttrRegex.FindStringSubmatch(header)
		if len(pathMatch) < 2 {
			pos = openTagEnd
			continue
		}
		targetPath := filepath.Clean(strings.TrimSpace(pathMatch[1]))

		switch {
		case strings.HasPrefix(strings.ToLower(header), "\x3c"+"del"+"ete"):
			actions = append(actions, Action{
				Type: ActionDelete,
				Path: targetPath,
				Line: lineNo,
			})
			pos = openTagEnd

		case strings.HasPrefix(strings.ToLower(header), "\x3c"+"fi"+"le"):
			if isSelfClosing {
				pos = openTagEnd
				continue
			}

			closeRe := regexp.MustCompile("(?i)\x3c/" + "fi" + "le\\s*>")
			m := closeRe.FindStringIndex(content[openTagEnd:])
			if m == nil {
				errs = append(errs, fmt.Sprintf("Line %d: Unclosed \x3c"+"fi"+"le path=\"%s\"> (no matching \x3c/"+"fi"+"le> found)", lineNo, targetPath))
				pos = openTagEnd
				continue
			}

			closeIdx := m[0]
			body := content[openTagEnd : openTagEnd+closeIdx]

			// Anti-corruption: only flag if a top-level unindented patch directive was swallowed
			if topLevelDirective.MatchString(body) {
				errs = append(errs, fmt.Sprintf("Line %d: Corrupted patch! \x3c"+"fi"+"le path=\"%s\"> appears to swallow another top-level directive before \x3c/"+"fi"+"le>.", lineNo, targetPath))
				pos = openTagEnd + m[1]
				continue
			}

			body = trimTagNewlines(body)
			body = stripCodeFences(body)

			actions = append(actions, Action{
				Type: ActionFile,
				Path: targetPath,
				Body: body,
				Line: lineNo,
			})
			pos = openTagEnd + m[1]

		case strings.HasPrefix(strings.ToLower(header), "\x3c"+"rep"+"lace"):
			if isSelfClosing {
				pos = openTagEnd
				continue
			}

			closeRe := regexp.MustCompile("(?i)\x3c/" + "rep" + "lace\\s*>")
			m := closeRe.FindStringIndex(content[openTagEnd:])
			if m == nil {
				errs = append(errs, fmt.Sprintf("Line %d: Unclosed \x3c"+"rep"+"lace path=\"%s\"> (no matching \x3c/"+"rep"+"lace> found)", lineNo, targetPath))
				pos = openTagEnd
				continue
			}

			inner := content[openTagEnd : openTagEnd+m[0]]

			searchMatch := searchRegex.FindStringSubmatch(inner)
			withMatch := withRegex.FindStringSubmatch(inner)

			if len(searchMatch) < 2 {
				if topLevelDirective.MatchString(inner) {
					errs = append(errs, fmt.Sprintf("Line %d: Corrupted patch! Unclosed directive detected inside \x3c"+"rep"+"lace path=\"%s\">", lineNo, targetPath))
				} else {
					errs = append(errs, fmt.Sprintf("Line %d: \x3c"+"rep"+"lace path=\"%s\"> is missing \x3c"+"sea"+"rch> block", lineNo, targetPath))
				}
				pos = openTagEnd + m[1]
				continue
			}
			if len(withMatch) < 2 {
				errs = append(errs, fmt.Sprintf("Line %d: \x3c"+"rep"+"lace path=\"%s\"> is missing \x3c"+"wi"+"th> block", lineNo, targetPath))
				pos = openTagEnd + m[1]
				continue
			}

			searchStr := trimTagNewlines(searchMatch[1])
			withStr := trimTagNewlines(withMatch[1])

			actions = append(actions, Action{
				Type:   ActionReplace,
				Path:   targetPath,
				Search: searchStr,
				With:   withStr,
				Line:   lineNo,
			})
			pos = openTagEnd + m[1]
		}
	}

	return actions, errs
}
