package main

import (
	"fmt"
	"html"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type ActionType int

const (
	ActionFile ActionType = iota
	ActionReplace
	ActionDelete
)

type Action struct {
	Type   ActionType
	Path   string
	Body   string // For ActionFile
	Search string // For ActionReplace
	With   string // For ActionReplace
	Line   int
}

var (
	pathAttrRegex     = regexp.MustCompile(`(?i)\bpath\s*=\s*["'“]([^"'”]+)["'”]`)
	tagStartRegex     = regexp.MustCompile(`(?i)<(file|replace|delete)\b`)
	searchRegex       = regexp.MustCompile(`(?s)<search\s*>(.*?)</search\s*>`)
	withRegex         = regexp.MustCompile(`(?s)<with\s*>(.*?)</with\s*>`)
	topLevelDirective = regexp.MustCompile(`(?m)^<(file|replace|delete)\b[^>]*\bpath\s*=`)
)

func cleanContent(s string) string {
	s = strings.ReplaceAll(s, "“", "\"")
	s = strings.ReplaceAll(s, "”", "\"")
	s = strings.ReplaceAll(s, "‘", "'")
	s = strings.ReplaceAll(s, "’", "'")
	if strings.Contains(s, "&lt;") || strings.Contains(s, "&gt;") {
		s = html.UnescapeString(s)
	}
	return s
}

// trimTagNewlines strips a single leading newline after <tag> and trailing newline before </tag>
func trimTagNewlines(s string) string {
	if strings.HasPrefix(s, "\r\n") {
		s = s[2:]
	} else if strings.HasPrefix(s, "\n") {
		s = s[1:]
	}

	if strings.HasSuffix(s, "\r\n") {
		s = s[:len(s)-2]
	} else if strings.HasSuffix(s, "\n") {
		s = s[:len(s)-1]
	}
	return s
}

// stripCodeFences removes accidental markdown code block wrappers generated by LLMs
func stripCodeFences(s string) string {
	trimmed := strings.TrimSpace(s)
	if !strings.HasPrefix(trimmed, "```") {
		return s
	}
	lines := strings.Split(s, "\n")
	startIdx := -1
	endIdx := -1

	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])
		if line != "" {
			if strings.HasPrefix(line, "```") {
				startIdx = i
			}
			break
		}
	}
	for i := len(lines) - 1; i >= 0; i-- {
		line := strings.TrimSpace(lines[i])
		if line != "" {
			if strings.HasPrefix(line, "```") {
				endIdx = i
			}
			break
		}
	}

	if startIdx != -1 && endIdx != -1 && startIdx < endIdx {
		return strings.Join(lines[startIdx+1:endIdx], "\n")
	}
	return s
}

func lineAtOffset(s string, offset int) int {
	if offset > len(s) {
		offset = len(s)
	}
	return strings.Count(s[:offset], "\n") + 1
}

func parsePatch(content string) ([]Action, []string) {
	var actions []Action
	var errs []string

	pos := 0
	for {
		loc := tagStartRegex.FindStringIndex(content[pos:])
		if loc == nil {
			break
		}

		startIdx := pos + loc[0]
		lineNo := lineAtOffset(content, startIdx)

		// Determine which tag opened
		openTagEnd := strings.Index(content[startIdx:], ">")
		if openTagEnd == -1 {
			errs = append(errs, fmt.Sprintf("Line %d: Malformed unclosed tag header", lineNo))
			break
		}
		openTagEnd += startIdx + 1
		header := content[startIdx:openTagEnd]

		// Ignore self-closing <file ... /> or <replace ... /> used in markdown/chat examples
		trimmedHeader := strings.TrimSpace(header)
		isSelfClosing := strings.HasSuffix(trimmedHeader, "/>")

		pathMatch := pathAttrRegex.FindStringSubmatch(header)
		if len(pathMatch) < 2 {
			pos = openTagEnd
			continue
		}
		targetPath := filepath.Clean(strings.TrimSpace(pathMatch[1]))

		switch {
		case strings.HasPrefix(strings.ToLower(header), "<delete"):
			actions = append(actions, Action{
				Type: ActionDelete,
				Path: targetPath,
				Line: lineNo,
			})
			pos = openTagEnd

		case strings.HasPrefix(strings.ToLower(header), "<file"):
			if isSelfClosing {
				// Inline chat reference like `<file path="..." />` — ignore safely
				pos = openTagEnd
				continue
			}

			closeRe := regexp.MustCompile(`(?i)</file\s*>`)
			m := closeRe.FindStringIndex(content[openTagEnd:])
			if m == nil {
				errs = append(errs, fmt.Sprintf("Line %d: Unclosed <file path=\"%s\"> (no matching </file> found)", lineNo, targetPath))
				pos = openTagEnd
				continue
			}

			closeIdx := m[0]
			body := content[openTagEnd : openTagEnd+closeIdx]

			// Anti-corruption: only flag if a top-level unindented patch directive was swallowed
			if topLevelDirective.MatchString(body) {
				errs = append(errs, fmt.Sprintf("Line %d: Corrupted patch! <file path=\"%s\"> appears to swallow another top-level directive before </file>.", lineNo, targetPath))
				pos = openTagEnd + m[1]
				continue
			}

			body = trimTagNewlines(body)
			body = stripCodeFences(body)

			actions = append(actions, Action{
				Type: ActionFile,
				Path: targetPath,
				Body: body,
				Line: lineNo,
			})
			pos = openTagEnd + m[1]

		case strings.HasPrefix(strings.ToLower(header), "<replace"):
			if isSelfClosing {
				pos = openTagEnd
				continue
			}

			closeRe := regexp.MustCompile(`(?i)</replace\s*>`)
			m := closeRe.FindStringIndex(content[openTagEnd:])
			if m == nil {
				errs = append(errs, fmt.Sprintf("Line %d: Unclosed <replace path=\"%s\"> (no matching </replace> found)", lineNo, targetPath))
				pos = openTagEnd
				continue
			}

			inner := content[openTagEnd : openTagEnd+m[0]]

			searchMatch := searchRegex.FindStringSubmatch(inner)
			withMatch := withRegex.FindStringSubmatch(inner)

			if len(searchMatch) < 2 {
				// Only flag if corrupted by an unclosed directive
				if topLevelDirective.MatchString(inner) {
					errs = append(errs, fmt.Sprintf("Line %d: Corrupted patch! Unclosed directive detected inside <replace path=\"%s\">", lineNo, targetPath))
				} else {
					errs = append(errs, fmt.Sprintf("Line %d: <replace path=\"%s\"> is missing <search> block", lineNo, targetPath))
				}
				pos = openTagEnd + m[1]
				continue
			}
			if len(withMatch) < 2 {
				errs = append(errs, fmt.Sprintf("Line %d: <replace path=\"%s\"> is missing <with> block", lineNo, targetPath))
				pos = openTagEnd + m[1]
				continue
			}

			searchStr := trimTagNewlines(searchMatch[1])
			withStr := trimTagNewlines(withMatch[1])

			actions = append(actions, Action{
				Type:   ActionReplace,
				Path:   targetPath,
				Search: searchStr,
				With:   withStr,
				Line:   lineNo,
			})
			pos = openTagEnd + m[1]
		}
	}

	return actions, errs
}

// performReplace uses a 4-tier fuzzy match: exact, CRLF-normalized, line-trimmed, and indentation-tolerant
func performReplace(origStr, search, with string) (string, bool) {
	// Tier 1: Exact match
	if strings.Contains(origStr, search) {
		return strings.Replace(origStr, search, with, 1), true
	}

	// Tier 2: CRLF / LF line ending normalization
	normalizedOrig := strings.ReplaceAll(origStr, "\r\n", "\n")
	normalizedSearch := strings.ReplaceAll(search, "\r\n", "\n")
	normalizedWith := strings.ReplaceAll(with, "\r\n", "\n")

	if strings.Contains(normalizedOrig, normalizedSearch) {
		res := strings.Replace(normalizedOrig, normalizedSearch, normalizedWith, 1)
		if strings.Contains(origStr, "\r\n") {
			res = strings.ReplaceAll(res, "\n", "\r\n")
		}
		return res, true
	}

	// Tier 3: Trailing whitespace tolerance on lines
	origLines := strings.Split(normalizedOrig, "\n")
	searchLines := strings.Split(normalizedSearch, "\n")

	if len(searchLines) <= len(origLines) {
		matchIdx := -1
		for i := 0; i <= len(origLines)-len(searchLines); i++ {
			matched := true
			for j := 0; j < len(searchLines); j++ {
				if strings.TrimRight(origLines[i+j], " \t\r") != strings.TrimRight(searchLines[j], " \t\r") {
					matched = false
					break
				}
			}
			if matched && matchIdx == -1 {
				matchIdx = i
				break
			}
		}
		if matchIdx != -1 {
			withLines := strings.Split(normalizedWith, "\n")
			newLines := make([]string, 0, len(origLines)-len(searchLines)+len(withLines))
			newLines = append(newLines, origLines[:matchIdx]...)
			newLines = append(newLines, withLines...)
			newLines = append(newLines, origLines[matchIdx+len(searchLines):]...)
			res := strings.Join(newLines, "\n")
			if strings.Contains(origStr, "\r\n") {
				res = strings.ReplaceAll(res, "\n", "\r\n")
			}
			return res, true
		}
	}

	// Tier 4: Indentation tolerance (TrimSpace block matching)
	if len(searchLines) <= len(origLines) {
		matchIdx := -1
		for i := 0; i <= len(origLines)-len(searchLines); i++ {
			matched := true
			for j := 0; j < len(searchLines); j++ {
				if strings.TrimSpace(origLines[i+j]) != strings.TrimSpace(searchLines[j]) {
					matched = false
					break
				}
			}
			if matched && matchIdx == -1 {
				matchIdx = i
				break
			}
		}
		if matchIdx != -1 {
			withLines := strings.Split(normalizedWith, "\n")
			newLines := make([]string, 0, len(origLines)-len(searchLines)+len(withLines))
			newLines = append(newLines, origLines[:matchIdx]...)
			newLines = append(newLines, withLines...)
			newLines = append(newLines, origLines[matchIdx+len(searchLines):]...)
			res := strings.Join(newLines, "\n")
			if strings.Contains(origStr, "\r\n") {
				res = strings.ReplaceAll(res, "\n", "\r\n")
			}
			return res, true
		}
	}

	return "", false
}

// findMismatchHint inspects where a search target almost matched to give actionable diagnostics
func findMismatchHint(origStr, search string) string {
	searchLines := strings.Split(strings.ReplaceAll(search, "\r\n", "\n"), "\n")
	if len(searchLines) == 0 {
		return ""
	}
	origLines := strings.Split(strings.ReplaceAll(origStr, "\r\n", "\n"), "\n")

	firstSearch := strings.TrimSpace(searchLines[0])
	if firstSearch == "" {
		return ""
	}

	for i, oLine := range origLines {
		if strings.TrimSpace(oLine) == firstSearch {
			for j := 1; j < len(searchLines) && i+j < len(origLines); j++ {
				s := strings.TrimRight(searchLines[j], " \t\r")
				f := strings.TrimRight(origLines[i+j], " \t\r")
				if s != f {
					return fmt.Sprintf("near target line %d:\n       Search: %q\n       Actual: %q", i+j+1, searchLines[j], origLines[i+j])
				}
			}
		}
	}
	return ""
}

type fileState struct {
	content []byte
	exists  bool
	deleted bool
}

func printUsage() {
	fmt.Println("Usage: patcher <patch-file.txt> [--dry-run]")
	fmt.Println("Options:")
	fmt.Println("  --dry-run, -n    Preview changes without writing to disk")
	fmt.Println("  --help, -h       Show this help message")
}

func main() {
	var patchFile string
	var dryRun bool

	for _, arg := range os.Args[1:] {
		switch arg {
		case "--dry-run", "-n":
			dryRun = true
		case "--help", "-h":
			printUsage()
			os.Exit(0)
		default:
			if strings.HasPrefix(arg, "-") {
				fmt.Fprintf(os.Stderr, "Unknown option: %s\n", arg)
				printUsage()
				os.Exit(1)
			}
			if patchFile == "" {
				patchFile = arg
			} else {
				fmt.Fprintf(os.Stderr, "Unexpected extra argument: %s\n", arg)
				printUsage()
				os.Exit(1)
			}
		}
	}

	if patchFile == "" {
		printUsage()
		os.Exit(1)
	}

	rawBytes, err := os.ReadFile(patchFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading %s: %v\n", patchFile, err)
		os.Exit(1)
	}

	content := cleanContent(string(rawBytes))
	actions, parseErrors := parsePatch(content)

	if len(parseErrors) > 0 {
		fmt.Fprintf(os.Stderr, "Patch syntax errors detected in %s:\n", patchFile)
		for _, pe := range parseErrors {
			fmt.Fprintf(os.Stderr, "  ✗ %s\n", pe)
		}
		fmt.Fprintln(os.Stderr, "\nAborted. No files were modified.")
		os.Exit(1)
	}

	if len(actions) == 0 {
		fmt.Printf("No actions matched in %s (file length: %d bytes).\n", patchFile, len(rawBytes))
		if strings.Contains(content, "<replace") || strings.Contains(content, "<file") {
			fmt.Println("Hint: Tags were found in the text, but the syntax didn't match the expected structure.")
		}
		os.Exit(1)
	}

	// PASS 1: In-Memory Simulation & Atomic Validation
	vfs := make(map[string]*fileState)
	getFile := func(path string) (*fileState, error) {
		if st, ok := vfs[path]; ok {
			return st, nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			if os.IsNotExist(err) {
				st := &fileState{exists: false}
				vfs[path] = st
				return st, nil
			}
			return nil, err
		}
		st := &fileState{content: b, exists: true}
		vfs[path] = st
		return st, nil
	}

	var simErrors []string
	for _, act := range actions {
		switch act.Type {
		case ActionFile:
			st, err := getFile(act.Path)
			if err != nil {
				simErrors = append(simErrors, fmt.Sprintf("Line %d: Error reading %s: %v", act.Line, act.Path, err))
				continue
			}
			st.content = []byte(act.Body)
			st.exists = true
			st.deleted = false

		case ActionDelete:
			st, err := getFile(act.Path)
			if err != nil {
				simErrors = append(simErrors, fmt.Sprintf("Line %d: Error reading %s: %v", act.Line, act.Path, err))
				continue
			}
			st.deleted = true

		case ActionReplace:
			st, err := getFile(act.Path)
			if err != nil {
				simErrors = append(simErrors, fmt.Sprintf("Line %d: Error reading %s: %v", act.Line, act.Path, err))
				continue
			}
			if !st.exists || st.deleted {
				simErrors = append(simErrors, fmt.Sprintf("Line %d: Cannot replace in %s: file does not exist", act.Line, act.Path))
				continue
			}
			newStr, ok := performReplace(string(st.content), act.Search, act.With)
			if !ok {
				hint := findMismatchHint(string(st.content), act.Search)
				errDesc := fmt.Sprintf("Line %d: ✗ Search target not found in: %s", act.Line, act.Path)
				if hint != "" {
					errDesc += fmt.Sprintf("\n     Mismatch hint %s", hint)
				}
				simErrors = append(simErrors, errDesc)
				continue
			}
			st.content = []byte(newStr)
		}
	}

	if len(simErrors) > 0 {
		fmt.Fprintf(os.Stderr, "Patch verification failed (%d errors):\n", len(simErrors))
		for _, se := range simErrors {
			fmt.Fprintf(os.Stderr, "  %s\n", se)
		}
		fmt.Fprintln(os.Stderr, "\nWorking tree left clean. Zero files were modified.")
		os.Exit(1)
	}

	// PASS 2: Commit verified changes to disk or preview dry-run
	for _, act := range actions {
		prefix := "✓"
		if dryRun {
			prefix = "[dry-run]"
		}

		switch act.Type {
		case ActionFile:
			if dryRun {
				fmt.Printf("%s WRITE %s (%d bytes)\n", prefix, act.Path, len(act.Body))
			} else {
				fmt.Printf("%s Wrote: %s\n", prefix, act.Path)
			}
		case ActionReplace:
			if dryRun {
				fmt.Printf("%s REPLACE in %s\n", prefix, act.Path)
			} else {
				fmt.Printf("%s Patched: %s\n", prefix, act.Path)
			}
		case ActionDelete:
			if dryRun {
				fmt.Printf("%s DELETE %s\n", prefix, act.Path)
			} else {
				fmt.Printf("%s Deleted: %s\n", prefix, act.Path)
			}
		}
	}

	if !dryRun {
		for path, st := range vfs {
			if st.deleted {
				if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
					fmt.Fprintf(os.Stderr, "Error deleting %s: %v\n", path, err)
				}
			} else if st.exists {
				if dir := filepath.Dir(path); dir != "." {
					if err := os.MkdirAll(dir, 0755); err != nil {
						fmt.Fprintf(os.Stderr, "Error creating directory %s: %v\n", dir, err)
						continue
					}
				}
				if err := os.WriteFile(path, st.content, 0644); err != nil {
					fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", path, err)
				}
			}
		}
	}

	if dryRun {
		fmt.Printf("\nDone. %d changes simulated successfully (dry-run).\n", len(actions))
	} else {
		fmt.Printf("\nDone. %d changes applied successfully.\n", len(actions))
	}
}
